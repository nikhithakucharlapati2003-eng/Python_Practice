# Python Program to Demonstrate Data Types

# Integer
age = 21

# Float
percentage = 85.5

# String
name = "Nikhitha"

# Boolean
is_student = True

# List
subjects = ["Python", "Java", "SQL"]

# Tuple
numbers = (10, 20, 30)

# Set
unique_numbers = {1, 2, 3, 4}

# Dictionary
student = {
    "name": "Nikhitha",
    "age": 21,
    "course": "Data Science"
}

# Display values and their data types
print("Integer:", age, type(age))
print("Float:", percentage, type(percentage))
print("String:", name, type(name))
print("Boolean:", is_student, type(is_student))
print("List:", subjects, type(subjects))
print("Tuple:", numbers, type(numbers))
print("Set:", unique_numbers, type(unique_numbers))
print("Dictionary:", student, type(student))
